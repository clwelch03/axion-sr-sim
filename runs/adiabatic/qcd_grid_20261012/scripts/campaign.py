def write_json(path, value):
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + '\n')
    temporary.replace(path)


def configure(case):
    """Isolated process only: restore every physical constant used by balance."""
    balance.MASS_SOLAR = case['mass_solar']
    balance.AXION_EV = case['axion_eV']
    balance.INITIAL_SPIN = .99
    balance.DECAY_CONSTANT_GEV = case['fa_GeV']
    balance.REFERENCE_TIME = G * case['mass_solar'] * balance.SOLAR_MASS_KG / c**3
    balance.INITIAL_ALPHA = case['alpha0']
    balance.EPSILON = (case['fa_GeV'] / balance.PLANCK_ENERGY_GEV)**2
    balance.INITIAL_CLOUD_FRACTIONS = SEEDS.copy()
    balance.INITIAL_CODE_ENERGIES = SEEDS / balance.EPSILON


def runtime_source_hashes():
    """Record shared solver files and campaign recipes without copying them.

    Paths are relative to the repository root. Exclude unrelated Dolan code
    and generated bytecode; changes to the recorded files invalidate a run.
    """
    files = []
    for directory in (SOURCE / 'adiabatic', SOURCE / 'common',
                      CAMPAIGN / 'scripts', CAMPAIGN / 'diagnostics'):
        files.extend(path for path in directory.rglob('*')
                     if path.is_file() and path.suffix in ('.py', '.jl', '.sh'))
    return {
        str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(files)
    }


def prepare():
    if (CAMPAIGN / 'manifest.json').exists():
        raise RuntimeError('Campaign already prepared; preserve its frozen inputs.')
    cases = []
    for mass_index, mass in enumerate(np.geomspace(2, 100, 10)):
        for axion_index, axion in enumerate(np.geomspace(1e-14, 1e-11, 10)):
            reference_time = G * mass * balance.SOLAR_MASS_KG / c**3
            alpha = reference_time * axion * electron_volt / hbar
            efolds = float(2 * growth_rate(alpha, .99) *
                           balance.YEAR_SECONDS / reference_time * AGE_YEARS)
            cases.append(dict(
                case_id=f'm{mass_index:02d}_a{axion_index:02d}',
                mass_index=mass_index, axion_index=axion_index,
                mass_solar=float(mass), axion_eV=float(axion),
                fa_GeV=float(5.7e6 / axion), alpha0=float(alpha),
                included=bool(alpha <= .45), initial_spin=.99, age_years=AGE_YEARS,
                initial_primary_fraction=float(SEEDS[0]),
                initial_secondary_fraction=float(SEEDS[1]),
                linear_primary_energy_efolds=efolds,
                method=('excluded_alpha' if alpha > .45 else
                        'small_alpha_age_screen' if alpha < .02 and efolds < 2 else
                        'coupled_stationary_track'),
            ))
    hashes = runtime_source_hashes()
    fingerprint = hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()
    manifest = dict(
        cases=cases, included_ids=[row['case_id'] for row in cases if row['included']],
        source_sha256=hashes, source_fingerprint=fingerprint,
        runtime_sha256=hashes,
        repository_revision=subprocess.check_output(
            ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        stopping_rules=dict(age_years=AGE_YEARS, spin_offset=.002,
                            relative_alpha_offset=1e-4, cloud_to_bh_mass=.10,
                            secondary_cubic_to_binding=.01),
        interpretation='Preliminary maxima over the valid simulated interval; stopped and screened cases are not completed nonlinear evolutions.',
    )
    write_json(CAMPAIGN / 'manifest.json', manifest)
    with (CAMPAIGN / 'grid.csv').open('w') as output:
        writer = csv.DictWriter(output, fieldnames=cases[0])
        writer.writeheader()
        writer.writerows(cases)
    print(f"Prepared {len(manifest['included_ids'])} included cases; "
          f"{sum(row['method'] == 'small_alpha_age_screen' for row in cases)} age screens.")


def load_manifest():
    manifest = json.loads((CAMPAIGN / 'manifest.json').read_text())
    # source_fingerprint identifies existing checkpoints. The separate runtime
    # hashes let a verified path-only cleanup preserve that historical identity
    # while still rejecting changes to the shared solvers or current launchers.
    for name, expected in manifest['runtime_sha256'].items():
        source = ROOT / name
        if not source.is_file() or hashlib.sha256(source.read_bytes()).hexdigest() != expected:
            raise RuntimeError(
                f'Campaign source changed or moved: {name}. '
                'Use its recorded source revision, or validate a new campaign; '
                'do not bypass the frozen source hashes.'
            )
    return manifest


def hydrogenic_peak(energy, alpha, l):
    """Real-field peak for a normalized n=l+1 hydrogenic mode; code units.

    Phi = sqrt(2 E)/mu Re[psi exp(-i omega t)], with integral |psi|^2=1.
    This is used ONLY in the explicitly labeled alpha<0.02 age screen.
    """
    principal = l + 1
    radial_constant = ((2 / principal)**1.5 /
                       math.sqrt(2 * principal * math.factorial(2 * l + 1)) *
                       (2 * l)**l * math.exp(-l))
    angular_constant = math.sqrt((2 * l + 1) * math.factorial(2 * l) /
                                 (4 * math.pi)) / (2**l * math.factorial(l))
    return np.sqrt(2 * energy) * alpha**2 * radial_constant * angular_constant


def stationary(directory, targets, manifest, tag):
    target_path = directory / f'{tag}_targets.csv'
    with target_path.open('w') as output:
        writer = csv.writer(output)
        writer.writerow(['label', 'alpha', 'spin', 'energy', 'step', 'outer'])
        writer.writerows(targets)
    output_dir = directory / 'stationary'
    subprocess.run([
        JULIA, f'--project={ROOT}', str(CAMPAIGN / 'scripts/stationary.jl'),
        str(SOURCE), str(target_path), str(output_dir), manifest['source_fingerprint'],
    ], check=True)
    return [np.genfromtxt(output_dir / f'{row[0]}.csv', names=True, delimiter=',')
            for row in targets]


def make_track(case, directory, manifest):
    # At small alpha, the cloud grows like alpha^-2 in radius. Preserve the
    # physical domain instead of reusing a 2000 M box that truncates it.
    outer = float(2 * math.ceil(max(800, 45 / case['alpha0']**2) / 2))
    step = .25
    initial_target = ['point000', case['alpha0'], .99,
                      float(balance.INITIAL_CODE_ENERGIES[0]), step, outer]
    initial = stationary(directory, [initial_target], manifest, 'initial')[0]
    frequency_ratio = float(initial['omega1'] / case['alpha0'])

    def pilot_rhs(loss, angular):
        mass_ratio = 1 - loss
        return [-mass_ratio / (frequency_ratio * case['alpha0'] * mass_ratio)]

    def pilot_threshold(loss, angular):
        mass_ratio = 1 - loss
        spin = angular[0] / mass_ratio**2
        if spin <= 0:
            return -1.
        horizon = spin / (2 * (1 + np.sqrt(1 - spin**2)))
        return horizon - frequency_ratio * case['alpha0'] * mass_ratio

    pilot_threshold.terminal = True
    pilot_threshold.direction = -1
    pilot = solve_ivp(pilot_rhs, (0, .3), [.99], events=pilot_threshold,
                      dense_output=True, rtol=1e-11, atol=1e-13)
    if not pilot.success or not len(pilot.t_events[0]):
        raise RuntimeError('Could not bracket the primary spin-down threshold.')
    loss_limit = float(pilot.t_events[0][0]) * 1.15
    # Continue the pilot only to place solve sites beyond primary saturation.
    pilot = solve_ivp(pilot_rhs, (0, loss_limit), [.99], dense_output=True,
                      rtol=1e-11, atol=1e-13)
    losses = np.r_[np.geomspace(loss_limit * 1e-5, loss_limit * .01, 5),
                   np.linspace(loss_limit * .05, loss_limit, 17)]
    targets = []
    for index, loss in enumerate(losses, 1):
        mass_ratio = 1 - loss
        spin = float(pilot.sol(loss)[0] / mass_ratio**2)
        if not 0 < spin < 1:
            raise RuntimeError('Pilot left the prograde Kerr domain.')
        targets.append([
            f'point{index:03d}', case['alpha0'] * mass_ratio, spin,
            float((SEEDS[0] + loss) / (balance.EPSILON * mass_ratio)), step, outer,
        ])
    stationary(directory, targets, manifest, 'track')
    return balance.StationaryTrack(directory / 'stationary')


def evolve_track(track, rtol=1e-7):
    def coordinate(state):
        return float(SEEDS[0] * np.exp(state[2]))

    def table_coordinate(state):
        # The ODE must evaluate just beyond terminal events to locate roots.
        # Clip ONLY those trial evaluations; the returned trajectory stops at
        # the table boundary and never extrapolates the stationary data.
        return np.clip(coordinate(state), track.coordinates[0], track.coordinates[-1])

    def coefficients(state):
        mass_ratio, spin, alpha, _ = balance.physical_state(state)
        if not mass_ratio > 0 or not 0 < spin < 1:
            raise RuntimeError('ODE trial left the Kerr domain.')
        location = table_coordinate(state)
        result = {name: float(track.splines[name](location)) for name in track.fields}
        horizon = spin / (2 * (1 + np.sqrt(1 - spin**2)))
        for name, omega, m in [('primary', 'omega1', 1), ('secondary', 'omega2', 2)]:
            response = track.splines[name + '_horizon_response'](location)
            result[name + '_horizon'] = float(response * (result[omega] - m * horizon))
        return result

    secondary_shape = CubicSpline(track.coordinates,
                                  track.rows['secondary_peak_per_sqrt_energy'])

    def margins(time, state):
        mass_ratio, spin, alpha, energies = balance.physical_state(state)
        location = table_coordinate(state)
        peak2 = float(secondary_shape(location)) * np.sqrt(energies[1])
        binding2 = 1 - (track.splines['omega2'](location) / alpha)**2
        return [
            coordinate(state) / track.coordinates[0] - .999,
            1 - coordinate(state) / track.coordinates[-1],
            1 - abs(spin - track.splines['spin'](location)) / .002,
            1 - abs(alpha / track.splines['alpha'](location) - 1) / 1e-4,
            1 - balance.EPSILON * sum(energies) / .10,
            1 - peak2**2 / (6 * max(float(binding2), 1e-30) * .01),
        ]

    names = ['primary_below_table', 'primary_above_table', 'spin_track_limit',
             'alpha_track_limit', 'cloud_mass_limit', 'secondary_nonlinearity_limit']
    events = []
    for index in range(len(names)):
        def event(time, state, index=index):
            return margins(time, state)[index]
        event.terminal = True
        event.direction = -1
        events.append(event)
    solution = solve_ivp(
        lambda time, state: balance.coupled_rhs(state, coefficients(state)),
        (0, AGE_YEARS), np.zeros(5), method='Radau', rtol=rtol,
        atol=np.array([1e-11, 1e-10, 1e-8, 1e-8, 1e-16]) * (rtol / 1e-7),
        events=events, dense_output=True,
    )
    if not solution.success:
        raise RuntimeError(solution.message)
    status = next((name for name, roots in zip(names, solution.t_events) if len(roots)),
                  'age_limit')
    return solution, status


def run_case(task_index):
    manifest = load_manifest()
    identifier = manifest['included_ids'][task_index]
    case = next(row for row in manifest['cases'] if row['case_id'] == identifier)
    configure(case)
    directory = CAMPAIGN / 'results' / identifier
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / 'writer.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        summary_path = directory / 'summary.json'
        if summary_path.exists():
            saved = json.loads(summary_path.read_text())
            if saved.get('source_fingerprint') != manifest['source_fingerprint']:
                raise RuntimeError('Existing case has a different source fingerprint.')
            if saved.get('finished'):
                print(f'{identifier}: already finished')
                return
        summary = dict(case, source_fingerprint=manifest['source_fingerprint'],
                       finished=False, status='running', slurm_job_id=os.getenv('SLURM_JOB_ID'))
        write_json(summary_path, summary)
        try:
            if case['method'] == 'small_alpha_age_screen':
                def linear_coefficients(state):
                    _, spin, alpha, _ = balance.physical_state(state)
                    return balance.independent_coefficients(alpha, spin)
                solution = balance.evolve(
                    linear_coefficients,
                    final_years=AGE_YEARS, max_step=AGE_YEARS / 100, rtol=1e-9,
                )
                status = 'age_limit_linear_screen'
                track = None
            else:
                track = make_track(case, directory, manifest)
                solution, status = evolve_track(track)
                refined, refined_status = evolve_track(track, rtol=1e-9)
                comparison_times = np.linspace(0, min(solution.t[-1], refined.t[-1]), 501)
                discrepancy = np.max(abs(
                    solution.sol(comparison_times)[:4] - refined.sol(comparison_times)[:4]))
                if status != refined_status or discrepancy > 1e-3:
                    raise RuntimeError(f'Time-refinement check failed: {discrepancy}')
                summary['time_refinement_state_error'] = float(discrepancy)

            final_time = float(solution.t[-1])
            times = np.unique(np.r_[solution.t, 0,
                np.geomspace(max(final_time * 1e-12, 1e-15), final_time, 1800)])
            states = solution.sol(times)
            mass_ratio = 1 - states[0]
            fractions = SEEDS[:, None] * np.exp(states[2:4])
            energies = fractions / (balance.EPSILON * mass_ratio)
            alpha = balance.INITIAL_ALPHA * mass_ratio
            if track is None:
                peaks = np.array([hydrogenic_peak(energies[i], alpha, i + 1) for i in range(2)])
                frequencies = np.array([alpha * (1 - alpha**2 / (2 * n**2)) for n in (2, 3)])
            else:
                location = np.clip(fractions[0], track.coordinates[0], track.coordinates[-1])
                primary_shape = CubicSpline(track.coordinates,
                    track.rows['primary_peak_envelope'] / np.sqrt(track.rows['energy']))
                secondary_shape = CubicSpline(track.coordinates,
                    track.rows['secondary_peak_per_sqrt_energy'])
                peaks = np.array([primary_shape(location) * np.sqrt(energies[0]),
                                  secondary_shape(location) * np.sqrt(energies[1])])
                frequencies = np.array([track.splines[name](location) for name in ('omega1', 'omega2')])
            # Sum of separate maxima is a conservative phase-envelope estimate
            # for the two bound clouds, not a measured coincident maximum.
            envelope = np.sum(peaks, axis=0)
            binding = np.min(1 - (frequencies / alpha)**2, axis=0)
            binding_ratio = envelope**2 / (6 * binding)
            if np.any(peaks < 0) or np.any(binding <= 0) or not np.all(np.isfinite(binding_ratio)):
                raise RuntimeError('Invalid field diagnostics')
            physical = balance.trajectory_array(solution, times)
            if np.max(abs(physical[:, -1])) > 1e-6:
                raise RuntimeError('Energy-balance audit failed')
            np.savetxt(directory / 'trajectory.csv',
                np.column_stack((physical, peaks.T, envelope, envelope * case['fa_GeV'],
                                 envelope**2 / 6, binding_ratio)), delimiter=',', comments='',
                header=balance.CSV_HEADER + ',primary_peak_over_fa,secondary_peak_over_fa,'
                       'bound_cloud_envelope_over_fa,bound_cloud_envelope_GeV,'
                       'cubic_over_mass,cubic_over_binding_scale')
            summary.update(
                finished=True, status=status, final_time_years=final_time,
                completed_nonlinear_age=(status == 'age_limit'),
                max_bound_cloud_envelope_over_fa=float(np.max(envelope)),
                max_primary_peak_over_fa=float(np.max(peaks[0])),
                max_secondary_peak_over_fa=float(np.max(peaks[1])),
                max_cubic_over_binding_scale=float(np.max(binding_ratio)),
                max_energy_audit=float(np.max(abs(physical[:, -1]))),
                final_spin=float(physical[-1, 1]),
                limitations='Sampled bound-cloud envelope; driven fields excluded. No GW loss or self-gravity. Stationary-track and secondary validity limits terminate incomplete runs.',
            )
            write_json(summary_path, summary)
            print(json.dumps(summary, indent=2))
        except Exception as error:
            summary.update(status='failed', error=str(error))
            write_json(summary_path, summary)
            traceback.print_exc()
            raise


def smoke_case(task_index):
    """Exercise the actual Julia adapter before releasing the production array."""
    manifest = load_manifest()
    identifier = manifest['included_ids'][task_index]
    case = next(row for row in manifest['cases'] if row['case_id'] == identifier)
    configure(case)
    directory = CAMPAIGN / 'results' / identifier
    directory.mkdir(parents=True, exist_ok=True)
    outer = float(2 * math.ceil(max(800, 45 / case['alpha0']**2) / 2))
    target = ['point000', case['alpha0'], .99,
              float(balance.INITIAL_CODE_ENERGIES[0]), .25, outer]
    row = stationary(directory, [target], manifest, 'initial')[0]
    if not (row['primary_peak_envelope'] >= row['peak_field'] * .999 and
            row['secondary_peak_per_sqrt_energy'] > 0):
        raise AssertionError('Invalid two-cloud field envelope')
    print(f"SMOKE PASSED {identifier} alpha={case['alpha0']}")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'run', 'smoke'])
    parser.add_argument('index', nargs='?', type=int)
    args = parser.parse_args()
    if args.action == 'prepare':
        prepare()
    else:
        if args.index is None:
            parser.error('run requires an array index')
        (run_case if args.action == 'run' else smoke_case)(args.index)
