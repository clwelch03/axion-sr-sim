"""Prepare and run the 10x10 QCD survey, with alpha0 <= 0.45.

Shared library source is hash-checked before execution. Each process configures the
existing single-run Python balance module once, then owns one case directory.
The 1-D stationary track is used only within its monitored validity region.
"""
